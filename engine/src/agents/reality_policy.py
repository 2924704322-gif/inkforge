"""现实性评判口径（用户要求 · 单一定义点）。

由来（用户原话）："面对用户可能不符合实际的创作需求，不需要因为现实原因修改，
以用户的创作目标为主给出修改建议，该规则对正文创作同样适用。"

这条要求必须落成**一处定义、四处注入**的常量，而不是散落在各模板里的软约定：
- 散落 = 各模板措辞漂移（历史上"两套防拒绝话术漂移"踩过同样的坑）；
- 只在编辑器里写 = 写手仍会为了"更合理"削弱作者设定，问题只是从评分挪到了正文。

语义（默认档：以作者目标为准）：
- 评判基准只有一条：是否与**作者给的 brief / 自定义约束 / 已确认设定**自洽；
- 现实合理性**不作为**评判依据，也不得作为修改建议的理由；
- 例外（唯一）：正文**违反作者自己已确认的设定**（吃书、自相矛盾）照常算真缺陷——
  那是"作者框架内的错误"，不是"现实性错误"。

显式开关（`allow_realism`）：作者可以在建书/创作需求处勾选「要求现实合理性约束」，
勾上后恢复"可以按现实逻辑提建议"的行为。默认关闭。
"""

from __future__ import annotations

from typing import Any

#: 结构化 brief 字段键（与 server.BriefFieldsBody / 前端 BriefFields 同名）
BRIEF_FIELD_KEY = "allow_realism"


def normalize_allow_realism(value: Any) -> bool:
    """把各种来源的取值归一为布尔。缺省/脏值一律 False（= 以作者目标为准）。"""
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return value != 0
    if isinstance(value, str):
        return value.strip().lower() in ("1", "true", "yes", "on", "是", "要", "开启")
    return False


def reality_policy_text(allow_realism: bool) -> str:
    """渲染注入正文的「现实性评判口径」段（四个生成/审查模板共用同一份文本）。"""
    if not allow_realism:
        return (
            "【现实性评判口径（刚性 · 作者未要求现实约束）】\n"
            "1. 唯一评判基准是**作者的创作目标**：设定、能力、社会规则、事件走向只需与"
            "【作者创作需求】【自定义创作约束】及已确认设定自洽即可，不需要符合现实世界的"
            "物理、生理、社会或常识。\n"
            "2. **禁止**以「不符合现实」「不够合理」「现实中不成立」「逻辑上说不通（指现实逻辑）」"
            "为由扣分、标注 issue 或提出修改建议。以此为理由的建议一律不得提出。\n"
            "3. 给出的所有建议都必须是**在作者设定框架内**「怎么写更好」（写法、节奏、具体度、"
            "情绪张力、可读性），而不是把作者的设定改成更贴近现实的样子。\n"
            "4. 唯一例外（照常算真缺陷）：产出**违反作者自己已确认的设定**——吃书、自相矛盾、"
            "与已给定的事实冲突。这属于「作者框架内的错误」，按原有标准处理。\n"
            "5. 作者的要求若与自身设定互相矛盾，可以用一条 minor 提示提醒作者，"
            "但不得据此要求改掉作者明确要的东西。"
        )
    return (
        "【现实性评判口径（作者已要求现实约束）】\n"
        "作者勾选了「要求现实合理性约束」：除与【作者创作需求】【自定义创作约束】及已确认设定"
        "自洽之外，还应当检查现实合理性——物理/生理/社会/常识层面的明显失真可以标注 issue "
        "并给出建议。\n"
        "但优先级不变：**作者明确要的东西优先于现实逻辑**；作者点名保留的设定，"
        "即使不符合现实也不得要求删除或改写，只能提示其代价与后果。"
    )
